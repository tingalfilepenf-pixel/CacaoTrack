    /**
     * CSV export of the Cacao Tree Stock Ledger (Phase 7C) — the same monthly
     * grid plus the nested batch summary, both read from the centralized
     * {@see AnalyticsMetrics::stockLedgerGrid()} (RULE 6/12). Generated live; no
     * report table (PRD §9, ERD §9.4).
     */
    public function exportLedgerCsv(Request $request): Response
    {
        $filters = $request->validate($this->ledgerRules());

        $grid = AnalyticsMetrics::stockLedgerGrid(
            $filters['batch_id'] ?? null,
            $filters['scion_variety_id'] ?? null,
            $filters['date_from'] ?? null,
            $filters['date_to'] ?? null,
        );

        $filename = 'cacao-stock-ledger-'.now()->format('Y-m-d').'.csv';
        $headers = [
            'Content-Type' => 'text/csv; charset=UTF-8',
            'Content-Disposition' => 'attachment; filename="'.$filename.'"',
        ];

        $sections = [
            'Grafted' => 'grafted',
            'Mortality' => 'mortality',
            'Regraft' => 'regraft',
            'Ready to Plant' => 'ready',
            'Pullout' => 'pullout',
        ];
        $varieties = $grid['varieties'];

        $handle = fopen('php://temp', 'r+');

        fputcsv($handle, ['Cacao Tree Stock Ledger']);
        fputcsv($handle, ['Generated', now()->format('M j, Y g:i A')]);
        fputcsv($handle, ['Generated By', (string) $request->user()->name]);
        fputcsv($handle, ['Filters', $this->ledgerLabel($filters)]);

        fputcsv($handle, []);
        fputcsv($handle, ['Monthly Grid']);

        $columnHeaders = ['Month', 'Date', 'Description', 'Seedlings'];

        foreach ($sections as $label => $key) {
            if ($varieties === []) {
                $columnHeaders[] = $label;

                continue;
            }

            foreach ($varieties as $variety) {
                $columnHeaders[] = $label.' - '.$variety['name'];
            }
        }

        fputcsv($handle, $columnHeaders);

        foreach ($grid['months'] as $month) {
            foreach ($month['rows'] as $row) {
                fputcsv($handle, $this->ledgerCsvLine($month['label'], (string) $row['date'], (string) $row['description'], $row, $sections, $varieties));
            }

            fputcsv($handle, $this->ledgerCsvLine(
                $month['label'],
                '',
                'TOTAL — '.$month['label'],
                $this->ledgerCsvTotals($month['totals']),
                $sections,
                $varieties,
            ));
        }

        fputcsv($handle, $this->ledgerCsvLine(
            'All months',
            '',
            'GRAND TOTAL',
            $this->ledgerCsvTotals($grid['grandTotals']),
            $sections,
            $varieties,
        ));

        fputcsv($handle, []);
        fputcsv($handle, ['Sub-batch quantities appear under Regraft, not Grafted. A regraft from a sub-batch is a further movement of the same plants; no cross-column total is implied.']);

        fputcsv($handle, []);
        fputcsv($handle, ['Batch summary (nested)']);
        fputcsv($handle, ['Batch or sub-batch', 'Parent Batch', 'Scion Variety', 'Total Grafted', 'Available', 'Regraft', 'Mortality', 'Stock Out', 'Date Grafted']);

        foreach ($grid['batchSummary']['rows'] as $row) {
            $label = ($row['depth'] > 0 ? str_repeat('  ', $row['depth']).'↳ ' : '').$row['batch'];
            $label .= $row['parent_missing'] && $row['parent'] ? ' (parent: '.$row['parent'].')' : '';

            fputcsv($handle, [
                $label,
                $row['parent'] ?? '',
                $row['variety'],
                $row['total_grafted'],
                $row['available'],
                $row['regraft'],
                $row['mortality'],
                $row['stock_out'],
                $row['grafted_date'] ?? '',
            ]);
        }

        $totals = $grid['batchSummary']['totals'];
        fputcsv($handle, [
            'Total', '', '',
            $totals['total_grafted'], $totals['available'], $totals['regraft'], $totals['mortality'], $totals['stock_out'], '',
        ]);

        rewind($handle);
        $csv = (string) stream_get_contents($handle);
        fclose($handle);

        return response($csv, 200, $headers);
    }

    /**
     * One CSV line for the monthly grid (shared by event and TOTAL rows).
     *
     * @param  array<string,mixed>  $row
     * @param  array<string,string>  $sections
     * @param  array<int,array{id:int,name:string}>  $varieties
     * @return array<int,mixed>
     */
    protected function ledgerCsvLine(string $monthLabel, string $date, string $description, array $row, array $sections, array $varieties): array
    {
        $line = [$monthLabel, $date, $description, (int) $row['seedlings'] > 0 ? $row['seedlings'] : ''];

        foreach ($sections as $key) {
            if ($varieties === []) {
                $line[] = '';

                continue;
            }

            foreach ($varieties as $variety) {
                $value = (int) ($row[$key][$variety['id']] ?? 0);
                $line[] = $value > 0 ? $value : '';
            }
        }

        return $line;
    }

    /**
     * Shape a month/grand-total array for {@see ledgerCsvLine()} (seedlings plus
     * each per-variety dimension).
     *
     * @param  array<string,mixed>  $totals
     * @return array<string,mixed>
     */
    protected function ledgerCsvTotals(array $totals): array
    {
        $row = ['seedlings' => (int) ($totals['seedlings'] ?? 0)];

        foreach (['grafted', 'mortality', 'regraft', 'ready', 'pullout'] as $key) {
            $row[$key] = (array) ($totals[$key] ?? []);
        }

        return $row;
    }

    /**
     * Tabular deliverable: Mortality Root-Cause Matrix (PRD §9.4).
     */
    public function mortalityMatrix(Request $request)
    {
        $filters = $request->validate($this->matrixRules());

        $matrix = AnalyticsMetrics::mortalityMatrix(
            $filters['batch_id'] ?? null,
            $filters['scion_variety_id'] ?? null,
            $filters['date_from'] ?? null,
            $filters['date_to'] ?? null,
        );

        $baseline = $this->latestMatrixReport($filters);

        $alerts = AnalyticsMetrics::mortalityMatrixRegressions(
            $matrix,
            $baseline?->result_summary,
        );

        // Transient feedback for the current render: no table, no persistence
        // (PRD §15, ERD §9.5). now() keeps it to this request only.
        if (($message = $this->mortalityIncreaseToast($alerts)) !== null) {
            $request->session()->now('warning', $message);
        }

        return view('analytics.mortality-matrix', array_merge(
            $this->filterOptions(),
            [
                'matrix' => $matrix,
                'filters' => $filters,
                'matrixBaseline' => $baseline,
                'alerts' => $alerts,
                'reports' => $this->reportsFor(Analytic::TYPE_MORTALITY_MATRIX),
            ],
        ));
    }

    /**
     * Build the toast message for a detected mortality increase, or null when
     * nothing increased. Centralized here so the wording stays with the rule
     * (RULE 6); the toast itself is the transient session-flash surface (PRD §15).
     *
     * @param  array{hasBaseline:bool,causes:array<int,array{cause:string,previous:int,current:int,increase:int}>,cells:array<int,array{variety:string,cause:string,previous:int,current:int,increase:int}>}  $alerts
     */
    protected function mortalityIncreaseToast(array $alerts): ?string
    {
        $causes = $alerts['causes'] ?? [];
        $cells = $alerts['cells'] ?? [];

        if ($causes === [] && $cells === []) {
            return null;
        }

        if ($causes !== []) {
            $parts = array_map(
                fn (array $alert): string => sprintf(
                    '%s %s → %s (+%s)',
                    $alert['cause'],
                    number_format($alert['previous']),
                    number_format($alert['current']),
                    number_format($alert['increase']),
                ),
                array_slice($causes, 0, 3),
            );

            $summary = implode('; ', $parts);

            if (count($causes) > 3) {
                $summary .= ' and '.number_format(count($causes) - 3).' more cause(s)';
            }
        } else {
            $summary = number_format(count($cells)).' variety/cause cell(s) increased';
        }

        return 'Mortality increased since the last saved Root-Cause Matrix report: '.$summary.'.';
    }

    /**
     * The most recent generated Mortality Root-Cause Matrix snapshot whose
     * applied filters match the ones currently selected — used as the baseline
     * for the mortality-increase alert. Snapshots are the ERD `Analytics`
     * report-generation history (ERD §9.4); no new table/column (PRD §9, RULE 4).
     *
     * @param  array<string,mixed>  $filters
     */
    protected function latestMatrixReport(array $filters): ?Analytic
    {
        $period = $this->periodLabel($filters['date_from'] ?? null, $filters['date_to'] ?? null);
        $currentVariety = $filters['scion_variety_id'] ?? null;

        return Analytic::query()
            ->where('analysis_type', Analytic::TYPE_MORTALITY_MATRIX)
            ->where('analysis_period', $period)
            ->orderByDesc('generated_at')
            ->get()
            ->first(function (Analytic $report) use ($filters, $currentVariety): bool {
                $stored = $report->result_summary['filters'] ?? null;

                // Legacy snapshot without filter metadata: only comparable when the
                // current view is not narrowed by batch/variety.
                if (! is_array($stored)) {
                    return empty($filters['batch_id']) && empty($currentVariety);
                }

                // Accept the revised `scion_variety_id` key, falling back to the
                // pre-P5 `variety_id` key for legacy snapshots.
                $storedVariety = $stored['scion_variety_id'] ?? ($stored['variety_id'] ?? null);

                return (string) ($stored['batch_id'] ?? '') === (string) ($filters['batch_id'] ?? '')
                    && (string) $storedVariety === (string) $currentVariety
                    && (string) ($stored['date_from'] ?? '') === (string) ($filters['date_from'] ?? '')
                    && (string) ($stored['date_to'] ?? '') === (string) ($filters['date_to'] ?? '');
            });
    }

