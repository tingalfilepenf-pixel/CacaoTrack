     * @return array{scionVarieties:Collection,batches:Collection}
     */
    protected function filterOptions(): array
    {
        return [
            'scionVarieties' => ScionVariety::orderBy('scion_variety_name')->get(),
            // Ordered by the tree helper in the views so sub-batches sit under
            // their parent (Phase 7C). The filter still matches the exact batch.
            'batches' => Batch::with('scionVariety')->get(),
        ];
    }

    /**
     * Saved report snapshots for one report type (the ERD `Analytics` entity is
     * report-generation history). Displayed on the page that produced them so
     * Generate Report has visible, traceable output.
     *
     * @return Collection<int,Analytic>
     */
    protected function reportsFor(string $type, int $limit = 10): Collection
    {
        return Analytic::with('user')
            ->where('analysis_type', $type)
            ->orderByDesc('generated_at')
            ->limit($limit)
            ->get();
    }

    protected function periodLabel(?string $from, ?string $to): string
    {
        if (! $from && ! $to) {
            return 'All time';
        }

        if ($from && $to) {
            return $from.' to '.$to;
        }

        return $from ? 'From '.$from : 'Until '.$to;
    }

    /**
     * Human-readable description of the applied stock-ledger filters, shown on
     * the printable PDF so the report is self-describing (traceability).
     *
     * @param  array<string,mixed>  $filters
     */
    protected function ledgerLabel(array $filters): string
    {
        return $this->filterLabel($filters, 'All batches');
    }

    /**
     * Human-readable description of the applied matrix filters (variety/batch/
     * period), shown on the printable PDF so the report is self-describing.
     *
     * @param  array<string,mixed>  $filters
     */
    protected function matrixLabel(array $filters): string
    {
        return $this->filterLabel($filters, 'All scion varieties (all time)');
    }

    /**
     * Human-readable description of the applied gap-report filters
     * (variety/batch), shown on the printable PDF (traceability).
     *
     * @param  array<string,mixed>  $filters
     */
    protected function gapLabel(array $filters): string
    {
        return $this->filterLabel($filters, 'All batches (all time)', withPeriod: false);
    }

    /**
     * Build the self-describing filter label shared by the printable reports
     * (RULE 6): the period (when applicable) plus any selected batch/variety.
     *
     * @param  array<string,mixed>  $filters
     */
    protected function filterLabel(array $filters, string $empty, bool $withPeriod = true): string
    {
        $parts = [];

        if ($withPeriod) {
            $period = $this->periodLabel($filters['date_from'] ?? null, $filters['date_to'] ?? null);
            if ($period !== 'All time') {
                $parts[] = $period;
            }
        }

        if (! empty($filters['batch_id'])) {
            $code = Batch::whereKey($filters['batch_id'])->value('batch_code');
            $parts[] = 'Batch: '.($code ?? '#'.$filters['batch_id']);
        }

        if (! empty($filters['scion_variety_id'])) {
            $name = ScionVariety::whereKey($filters['scion_variety_id'])->value('scion_variety_name');
            $parts[] = 'Scion Variety: '.($name ?? '#'.$filters['scion_variety_id']);
        }

        return $parts === [] ? $empty : implode('  |  ', $parts);
    }
