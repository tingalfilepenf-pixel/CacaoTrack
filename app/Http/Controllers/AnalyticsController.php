     */
    public function generate(Request $request)
    {
        $data = $request->validate(Analytic::rules());

        $from = $data['date_from'] ?? null;
        $to = $data['date_to'] ?? null;
        $period = $this->periodLabel($from, $to);

        Analytic::create([
            'user_id' => $request->user()->id,
            'analysis_type' => $data['analysis_type'],
            'analysis_period' => $period,
            'result_summary' => AnalyticsMetrics::summaryFor($data['analysis_type'], $data),
            'generated_at' => now(),
        ]);

        ActivityLog::record(
            null,
            ActivityLog::TYPE_REPORT_GENERATED,
            "Generated {$data['analysis_type']} report ({$period}).",
        );

        return back()->with('success', 'Analytics report generated successfully.');
    }

    /**
