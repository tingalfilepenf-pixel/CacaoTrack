     * @return array<string,array<int,string>>
     */
    protected function gapRules(): array
    {
        return [
            'batch_id' => ['nullable', 'integer', 'exists:batches,batch_id'],
            'scion_variety_id' => ['nullable', 'integer', 'exists:scion_varieties,scion_variety_id'],
        ];
    }

